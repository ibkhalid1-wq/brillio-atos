export async function extractGovernContextFromDocument(
  doc: { text: string; name: string; usableText: boolean },
  _existingGovern: Record<string, any> = {},
): Promise<{
  capturedRisks: string[];
  agentRegistryEntries: Array<{ agentName: string; missionStatement: string; autonomyLevel: string }>;
  complianceControlGaps: string[];
  hitlTriggers: string[];
}> {
  if (!doc?.usableText || !doc?.text?.trim()) {
    return { capturedRisks: [], agentRegistryEntries: [], complianceControlGaps: [], hitlTriggers: [] };
  }
  const system = `You are an AI governance analyst extracting governance artifacts from a document.
Return JSON only — no markdown, no explanation.
Shape: {
  "capturedRisks": ["risk descriptions — max 5"],
  "agentRegistryEntries": [{ "agentName": "...", "missionStatement": "...", "autonomyLevel": "supervised|semi-autonomous|autonomous" }],
  "complianceControlGaps": ["gap descriptions — max 4"],
  "hitlTriggers": ["trigger conditions — max 4"]
}
Only extract what is explicitly present. Return empty arrays if nothing found.`;
  const user = `Document: ${doc.name}\n\n${doc.text.slice(0, 4000)}`;
  try {
    const raw = await requestAIText(system, user, { max_tokens: 900 });
    const start = String(raw ?? "").indexOf("{");
    const end = String(raw ?? "").lastIndexOf("}");
    if (start === -1 || end === -1) {
      return { capturedRisks: [], agentRegistryEntries: [], complianceControlGaps: [], hitlTriggers: [] };
    }
    return JSON.parse(String(raw).slice(start, end + 1));
  } catch {
    return { capturedRisks: [], agentRegistryEntries: [], complianceControlGaps: [], hitlTriggers: [] };
  }
}

