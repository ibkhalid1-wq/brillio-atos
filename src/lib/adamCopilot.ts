export async function extractArchitectureDecisionsFromDocument(
  doc: { text?: string; name?: string },
  existingDecisions: any[] = [],
): Promise<any[]> {
  if (!doc?.text?.trim() || doc.text.trim().length < 200) return [];

  const system = `You are extracting architecture decisions from a technical document. 
For each decision found, return a JSON array of objects with: 
{ title, rationale, chosenApproach, alternativesConsidered, tradeOffs, linkedCapabilityIds: [] }
Return ONLY decisions that are explicitly stated. Do not invent. Return [] if none found.`;

  const user = doc.text.slice(0, 5000);

  try {
    const raw = await callRegisteredRuntime(system, user, { max_tokens: 1200 });
    const jsonStr = String(raw || "").match(/\[[\s\S]*\]/)?.[0];
    if (!jsonStr) return [];
    const parsed = JSON.parse(jsonStr);
    if (!Array.isArray(parsed)) return [];

    const existingTitles = new Set(
      existingDecisions.map((decision: any) => String(decision.title || "").toLowerCase().trim()),
    );

    return parsed
      .filter((decision) => decision?.title && !existingTitles.has(String(decision.title).toLowerCase().trim()))
      .map((decision) => ({
        ...decision,
        id: Math.random().toString(36).slice(2, 10),
        decision: decision?.decision || decision?.chosenApproach || "",
        decisionTitle: decision?.decisionTitle || decision?.title || "",
        chosenOption: decision?.chosenOption || decision?.chosenApproach || decision?.decision || "",
        status: "draft",
        sourceDocuments: [doc.name || "uploaded document"],
        createdAt: new Date().toISOString(),
        sourceArtifactId: null,
        sourceArtifactPhase: null,
        autoGenerated: false,
        generatedAt: null,
        generatedVersion: null,
      }));
  } catch {
    return [];
  }
}

export async function extractValueMetricsFromDocument(
  doc: { text?: string; name?: string },
  existingKpis: any[] = [],
): Promise<{ kpiActuals: any[]; agentRoiAttribution: string; benefitRealizationNotes: string }> {
  if (!doc?.text?.trim() || doc.text.trim().length < 200) {
    return { kpiActuals: [], agentRoiAttribution: "", benefitRealizationNotes: "" };
  }

  const system = `You are extracting value realization metrics from a business report or value assessment document. 
Extract: kpiActuals (array of {name, baseline, actual, unit, achievedPercent}), agentRoiAttribution (string summary of agent ROI), benefitRealizationNotes (string).
Return as JSON. Use null for fields not found. Do not invent numbers.`;

  const user = doc.text.slice(0, 4000);

  try {
    const raw = await callRegisteredRuntime(system, user, { max_tokens: 800 });
    const parsed = JSON.parse(String(raw || "").match(/\{[\s\S]*\}/)?.[0] || "{}");
    const priorNames = new Set(
      existingKpis.map((kpi: any) => String(typeof kpi === "string" ? kpi : kpi?.name || "").toLowerCase().trim()).filter(Boolean),
    );
    const deduped = Array.isArray(parsed.kpiActuals)
      ? parsed.kpiActuals.filter((kpi: any) => {
          const key = String(typeof kpi === "string" ? kpi : kpi?.name || "").toLowerCase().trim();
          return key && !priorNames.has(key);
        })
      : [];
    return {
      kpiActuals: deduped,
      agentRoiAttribution: parsed.agentRoiAttribution || "",
      benefitRealizationNotes: parsed.benefitRealizationNotes || "",
    };
  } catch {
    return { kpiActuals: [], agentRoiAttribution: "", benefitRealizationNotes: "" };
  }
}

export async function extractStrategyContextFromDocument(
  doc: { text?: string; name?: string },
  _existingContext: any = {},
): Promise<{ objectives: Array<{ text: string; confidenceScore: number }>; constraints: Array<{ text: string; confidenceScore: number }> }> {
  if (!doc?.text?.trim() || doc.text.trim().length < 200) {
    return { objectives: [], constraints: [] };
  }
  const system = `You are extracting strategy objectives and constraints from an executive transformation document.
Return JSON only in this shape:
{"objectives":[{"text":"","confidenceScore":0.0}],"constraints":[{"text":"","confidenceScore":0.0}]}
Only include explicitly stated items. Confidence scores must be between 0 and 1.`;
  try {
    const raw = await callRegisteredRuntime(system, doc.text.slice(0, 4500), { max_tokens: 900 });
    const parsed = JSON.parse(String(raw || "").match(/\{[\s\S]*\}/)?.[0] || "{}");
    return {
      objectives: Array.isArray(parsed.objectives) ? parsed.objectives.filter((item: any) => item?.text).map((item: any) => ({ text: String(item.text).trim(), confidenceScore: Number(item.confidenceScore || 0.6) })) : [],
      constraints: Array.isArray(parsed.constraints) ? parsed.constraints.filter((item: any) => item?.text).map((item: any) => ({ text: String(item.text).trim(), confidenceScore: Number(item.confidenceScore || 0.6) })) : [],
    };
  } catch {
    return { objectives: [], constraints: [] };
  }
}

