type RuntimeMap = Record<string, (...args: any[]) => any>;

let runtime: RuntimeMap = {};

export function registerAdamCopilotRuntime(nextRuntime: RuntimeMap) {
  runtime = { ...runtime, ...(nextRuntime || {}) };
}

function invoke(name: string, args: any[]) {
  const fn = runtime[name];
  if (typeof fn !== "function") {
    throw new Error(`ATOS copilot runtime not registered for ${name}`);
  }
  return fn(...args);
}

